#!/usr/bin/env python3
"""Regenerate flake.nix, apps.json and the README app list from the registry.

The source of truth is registry.yml in ruby-gtk-project/.github: one entry per
app, naming the fork that holds its Ruby port and upstream's licence. Each fork
carries its own flake that outputs `packages.default` and `apps.default`, so
this flake composes them rather than rebuilding them — every port's runtime
gemdir, gemConfig and GTK closure stays in the port.

    nix run .#update

Set REGISTRY to a local registry.yml to work offline.
"""

import json
import os
import pathlib
import re
import sys
import urllib.request

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORG = "ruby-gtk-project"
BRANCH = "ruby"
REGISTRY_URL = f"https://raw.githubusercontent.com/{ORG}/.github/main/registry.yml"
BEGIN, END = "<!-- BEGIN GENERATED APP LIST -->", "<!-- END GENERATED APP LIST -->"


def registry():
    override = os.environ.get("REGISTRY")
    if override:
        return yaml.safe_load(pathlib.Path(override).read_text())
    with urllib.request.urlopen(REGISTRY_URL, timeout=60) as response:
        return yaml.safe_load(response.read())


def index():
    """Attribute name -> app metadata. The attribute is the fork name lowercased,
    which is also the gem name, so `nix run .#commit-rb` matches `gem install
    commit-rb`."""
    apps = {}
    for entry in registry():
        fork = entry["fork"].rstrip("/").rsplit("/", 1)[-1]
        apps[fork.lower()] = {
            "app": entry["app"],
            "fork": fork,
            "upstream": entry["repo"],
            "license": entry["license"],
            "homepage": f"https://github.com/{ORG}/{fork}",
        }
    return dict(sorted(apps.items()))


def render_flake(apps):
    inputs = "\n".join(
        f'    {name}.url = "github:{ORG}/{meta["fork"]}/{BRANCH}";\n'
        f'    {name}.inputs.nixpkgs.follows = "nixpkgs";'
        for name, meta in apps.items()
    )
    ports = "\n".join(f"        {name} = inputs.{name};" for name in apps)
    return f"""# Generated by scripts/update.py from the port registry. Do not edit by hand.
{{
  description = "Every {ORG} app as a Nix package";

  inputs = {{
    nixpkgs.url = "github:NixOS/nixpkgs/nixpkgs-unstable";
    systems.url = "github:nix-systems/default";

    # One input per port, each the `{BRANCH}` branch of its fork. `follows`
    # keeps all {len(apps)} of them on this flake's nixpkgs, so the closure is one
    # nixpkgs rather than {len(apps)}.
{inputs}
  }};

  outputs =
    inputs@{{ self, nixpkgs, systems, ... }}:
    let
      inherit (nixpkgs) lib;
      eachSystem = lib.genAttrs (import systems);
      pkgsFor = eachSystem (system: nixpkgs.legacyPackages.${{system}});

      ports = {{
{ports}
      }};

      # A port appears in `packages` once its own flake builds for this system.
      # A port mid-rollout, or one whose flake has not been regenerated yet, is
      # still in the inventory but not in `packages` — the same way krew.nix
      # only exposes plugins that have a build for your platform.
      packagesFor =
        system:
        lib.filterAttrs (_: drv: drv != null) (
          lib.mapAttrs (
            _: port:
            let
              set = port.packages or {{ }};
            in
            if set ? ${{system}} && set.${{system}} ? default then set.${{system}}.default else null
          ) ports
        );
    in
    {{
      overlays.default = import ./overlay.nix;

      packages = eachSystem packagesFor;

      apps = eachSystem (
        system:
        lib.mapAttrs (_: drv: {{
          type = "app";
          program = lib.getExe drv;
        }}) (packagesFor system)
      );

      # Every app in the registry, including any not yet buildable.
      inventory = lib.importJSON ./apps.json;

      checks = eachSystem packagesFor;

      formatter = eachSystem (system: pkgsFor.${{system}}.nixfmt-tree);
    }};
}}
"""


def render_list(apps):
    rows = "\n".join(
        f'| `{name}` | [{meta["app"]}]({meta["upstream"]}) | '
        f'[{meta["fork"]}]({meta["homepage"]}) | `{meta["license"]}` |'
        for name, meta in apps.items()
    )
    return (
        f"\n{len(apps)} apps.\n\n"
        "| Attribute | Upstream | Port | Licence |\n|---|---|---|---|\n"
        f"{rows}\n"
    )


def main():
    apps = index()
    (ROOT / "apps.json").write_text(json.dumps(apps, indent=1, sort_keys=True) + "\n")
    (ROOT / "flake.nix").write_text(render_flake(apps))

    readme = ROOT / "README.md"
    text = readme.read_text()
    if BEGIN not in text or END not in text:
        print("README.md is missing the generated-list markers", file=sys.stderr)
        return 1
    readme.write_text(
        re.sub(
            re.escape(BEGIN) + r".*?" + re.escape(END),
            BEGIN + render_list(apps) + END,
            text,
            flags=re.S,
        )
    )
    print(f"{len(apps)} apps written to apps.json, flake.nix and README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
